using System.Text;
using System.Text.Json;
using LocalSonar.Core;

namespace LocalSonar.Analysis.Issues;

public sealed record RuleInfo(string Id, Severity Severity, string? Name);

/// <summary>
/// The rules active in your SonarQube quality profile, with their severities.
/// Loaded from rules.json, which can be either:
///   - the raw JSON from SonarQube's /api/rules/search (saved from the browser), or
///   - a simple array: [ { "key": "S1144", "severity": "MAJOR", "name": "..." } ]
/// </summary>
public sealed class RuleCatalog
{
    private readonly Dictionary<string, RuleInfo> _rules = new(StringComparer.OrdinalIgnoreCase);

    public static RuleCatalog Empty { get; } = new();

    public int Count => _rules.Count;
    public bool IsLoaded => _rules.Count > 0;
    public IEnumerable<RuleInfo> Rules => _rules.Values;

    public RuleInfo? Find(string ruleId) => _rules.GetValueOrDefault(ruleId);

    public void Add(RuleInfo rule) => _rules[rule.Id] = rule;

    public static RuleCatalog LoadFromFile(string path)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(path), new JsonDocumentOptions
        {
            CommentHandling = JsonCommentHandling.Skip,
            AllowTrailingCommas = true,
        });

        var catalog = new RuleCatalog();
        var root = document.RootElement;

        if (root.ValueKind == JsonValueKind.Array)
        {
            foreach (var rule in root.EnumerateArray())
            {
                catalog.AddFromJson(rule, actives: null);
            }
        }
        else if (root.TryGetProperty("rules", out var rules))
        {
            root.TryGetProperty("actives", out var actives);
            foreach (var rule in rules.EnumerateArray())
            {
                catalog.AddFromJson(rule, actives.ValueKind == JsonValueKind.Object ? actives : null);
            }
        }

        return catalog;
    }

    internal void AddFromJson(JsonElement rule, JsonElement? actives)
    {
        var key = GetString(rule, "key");
        if (key is null)
        {
            return;
        }

        // Only C# Sonar rules ("csharpsquid:S1144"); skip other languages/external repositories.
        var colon = key.IndexOf(':');
        if (colon >= 0 && !key.StartsWith("csharpsquid:", StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        var id = colon >= 0 ? key[(colon + 1)..] : key;

        // Severity set on activation in the profile wins over the rule's default severity.
        var severity = Severity.Unknown;
        if (actives is { } a && a.TryGetProperty(key, out var activations) && activations.ValueKind == JsonValueKind.Array)
        {
            severity = activations.EnumerateArray().Select(ReadSeverity).DefaultIfEmpty(Severity.Unknown).Min();
        }

        if (severity == Severity.Unknown)
        {
            severity = ReadSeverity(rule);
        }

        Add(new RuleInfo(id, severity, GetString(rule, "name")));
    }

    /// <summary>"severity" (standard mode), else the highest "impacts[].severity" (MQR mode).</summary>
    private static Severity ReadSeverity(JsonElement element)
    {
        var severity = SeverityParser.Parse(GetString(element, "severity"));
        if (severity != Severity.Unknown)
        {
            return severity;
        }

        if (element.TryGetProperty("impacts", out var impacts) && impacts.ValueKind == JsonValueKind.Array)
        {
            return impacts.EnumerateArray()
                .Select(i => SeverityParser.Parse(GetString(i, "severity")))
                .DefaultIfEmpty(Severity.Unknown)
                .Min();
        }

        return Severity.Unknown;
    }

    private static string? GetString(JsonElement element, string property) =>
        element.ValueKind == JsonValueKind.Object
        && element.TryGetProperty(property, out var value)
        && value.ValueKind == JsonValueKind.String
            ? value.GetString()
            : null;

    public void SaveSimpleFormat(string path)
    {
        var rows = _rules.Values
            .OrderBy(r => r.Id, StringComparer.OrdinalIgnoreCase)
            .Select(r => new { key = r.Id, severity = r.Severity.ToString().ToUpperInvariant(), name = r.Name });
        File.WriteAllText(path, JsonSerializer.Serialize(rows, new JsonSerializerOptions { WriteIndented = true }));
    }

    /// <summary>
    /// A .globalconfig that turns on every rule in the profile (SonarAnalyzer only enables
    /// "Sonar way" rules by default, but your company profile may enable more).
    /// </summary>
    public void WriteGlobalConfig(string path)
    {
        var sb = new StringBuilder()
            .AppendLine("# Generated by LocalSonar from the quality profile rules file.")
            .AppendLine("is_global = true")
            .AppendLine("global_level = 100")
            .AppendLine();

        foreach (var rule in _rules.Values.OrderBy(r => r.Id, StringComparer.OrdinalIgnoreCase))
        {
            sb.AppendLine($"dotnet_diagnostic.{rule.Id}.severity = warning");
        }

        File.WriteAllText(path, sb.ToString());
    }
}
