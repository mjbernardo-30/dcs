using System.Collections.Concurrent;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace LocalSonar.Analysis.Duplication;

/// <summary>Token stream for one file. Token text is interned to ints so comparisons are cheap.</summary>
public sealed record TokenizedFile(
    string FilePath,
    string RelativePath,
    int TotalLines,
    int[] TokenIds,
    int[] StartLines,
    int[] EndLines);

/// <summary>
/// Turns C# into the token stream Sonar's copy-paste detection compares:
/// literals are normalized (so code differing only in a string/number still counts as duplicated),
/// comments/whitespace are ignored, and using directives are skipped.
/// </summary>
public sealed class CpdTokenizer
{
    private readonly ConcurrentDictionary<string, int> _ids = new(StringComparer.Ordinal);
    private int _nextId;

    public TokenizedFile? Tokenize(string filePath, string relativePath)
    {
        var text = SourceText.From(File.ReadAllText(filePath));
        if (IsGenerated(filePath, text))
        {
            return null;
        }

        var root = CSharpSyntaxTree.ParseText(text, path: filePath).GetRoot();

        var ids = new List<int>();
        var startLines = new List<int>();
        var endLines = new List<int>();

        foreach (var token in root.DescendantTokens())
        {
            if (token.IsKind(SyntaxKind.EndOfFileToken) || token.IsMissing
                || token.Parent?.AncestorsAndSelf().Any(n => n is UsingDirectiveSyntax) == true)
            {
                continue;
            }

            var span = text.Lines.GetLinePositionSpan(token.Span);
            ids.Add(Intern(Normalize(token)));
            startLines.Add(span.Start.Line + 1);
            endLines.Add(span.End.Line + 1);
        }

        return new TokenizedFile(filePath, relativePath, text.Lines.Count, [.. ids], [.. startLines], [.. endLines]);
    }

    private static string Normalize(SyntaxToken token) => token.Kind() switch
    {
        SyntaxKind.NumericLiteralToken => "$num",
        SyntaxKind.StringLiteralToken
            or SyntaxKind.InterpolatedStringTextToken
            or SyntaxKind.SingleLineRawStringLiteralToken
            or SyntaxKind.MultiLineRawStringLiteralToken
            or SyntaxKind.Utf8StringLiteralToken => "$str",
        SyntaxKind.CharacterLiteralToken => "$char",
        _ => token.Text,
    };

    private int Intern(string value) => _ids.GetOrAdd(value, _ => Interlocked.Increment(ref _nextId));

    private static bool IsGenerated(string filePath, SourceText text)
    {
        var name = Path.GetFileName(filePath);
        if (name.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || name.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
            || name.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            || name.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || name.EndsWith("AssemblyInfo.cs", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        var head = text.ToString(new TextSpan(0, Math.Min(text.Length, 2000)));
        return head.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }
}
